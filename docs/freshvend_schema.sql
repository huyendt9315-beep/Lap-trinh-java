BEGIN;

CREATE TABLE roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role_id BIGINT NOT NULL REFERENCES roles(id),
    active BOOLEAN NOT NULL
);

CREATE TABLE machines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    location TEXT NOT NULL,
    status TEXT NOT NULL,
    min_c NUMERIC NOT NULL,
    max_c NUMERIC NOT NULL,
    degraded_message TEXT NOT NULL,
    last_seen_at TIMESTAMPTZ
);

CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    image_url TEXT NOT NULL,
    price_vnd BIGINT NOT NULL,
    active BOOLEAN NOT NULL
);

CREATE TABLE slots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    machine_id BIGINT NOT NULL REFERENCES machines(id),
    slot_no INTEGER NOT NULL,
    product_id BIGINT REFERENCES products(id),
    capacity INTEGER NOT NULL,
    low_threshold INTEGER NOT NULL,
    UNIQUE (machine_id, slot_no)
);

CREATE TABLE stock_lots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slot_id BIGINT NOT NULL REFERENCES slots(id),
    product_id BIGINT NOT NULL REFERENCES products(id),
    operator_id BIGINT NOT NULL REFERENCES users(id),
    received_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    qty_in INTEGER NOT NULL,
    qty_on_hand INTEGER NOT NULL
);

CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    machine_id BIGINT NOT NULL REFERENCES machines(id),
    location_at_sale TEXT NOT NULL,
    receipt_no TEXT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL,
    status TEXT NOT NULL,
    reservation_until TIMESTAMPTZ NOT NULL
);

CREATE TABLE order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id),
    product_id BIGINT NOT NULL REFERENCES products(id),
    qty INTEGER NOT NULL,
    unit_price_vnd BIGINT NOT NULL
);

CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id),
    request_key UUID NOT NULL UNIQUE,
    provider_ref TEXT,
    method TEXT NOT NULL,
    amount_vnd BIGINT NOT NULL,
    status TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    paid_at TIMESTAMPTZ
);

CREATE TABLE dispenses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id BIGINT NOT NULL REFERENCES order_items(id),
    lot_id BIGINT NOT NULL REFERENCES stock_lots(id),
    unit_no INTEGER NOT NULL,
    command_key UUID NOT NULL UNIQUE,
    status TEXT NOT NULL,
    delivered_at TIMESTAMPTZ,
    UNIQUE (item_id, unit_no)
);

CREATE TABLE attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dispense_id BIGINT NOT NULL REFERENCES dispenses(id),
    attempt_no INTEGER NOT NULL,
    result TEXT NOT NULL,
    event_key UUID NOT NULL UNIQUE,
    recorded_at TIMESTAMPTZ NOT NULL,
    UNIQUE (dispense_id, attempt_no)
);

CREATE TABLE refunds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id BIGINT NOT NULL REFERENCES payments(id),
    dispense_id BIGINT REFERENCES dispenses(id),
    request_key UUID NOT NULL UNIQUE,
    amount_vnd BIGINT NOT NULL,
    status TEXT NOT NULL,
    completed_at TIMESTAMPTZ
);

CREATE TABLE telemetry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    machine_id BIGINT NOT NULL REFERENCES machines(id),
    event_key UUID NOT NULL UNIQUE,
    measured_at TIMESTAMPTZ NOT NULL,
    received_at TIMESTAMPTZ NOT NULL,
    temp_c NUMERIC,
    humidity_pct NUMERIC,
    door_open BOOLEAN,
    device_state TEXT NOT NULL
);

CREATE TABLE alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    machine_id BIGINT NOT NULL REFERENCES machines(id),
    slot_id BIGINT REFERENCES slots(id),
    lot_id BIGINT REFERENCES stock_lots(id),
    dispense_id BIGINT REFERENCES dispenses(id),
    kind TEXT NOT NULL,
    severity TEXT NOT NULL,
    opened_at TIMESTAMPTZ NOT NULL,
    resolved_at TIMESTAMPTZ,
    resolved_by BIGINT REFERENCES users(id),
    resolution TEXT
);

CREATE TABLE outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_key UUID NOT NULL UNIQUE,
    event_type TEXT NOT NULL,
    payload JSONB NOT NULL,
    status TEXT NOT NULL,
    attempt_count INTEGER NOT NULL,
    next_try_at TIMESTAMPTZ NOT NULL,
    last_error TEXT
);

COMMIT;

SELECT table_name FROM information_schema.tables WHERE table_schema = 'public' AND table_type = 'BASE TABLE' ORDER BY table_name;
